// Time-locked links: the payload key is folded with the output of a
// sequential time puzzle, so the real key only appears after the grind.
// No server, no clock trust — just computational delay.
//
// Two mechanisms:
//   - RSW puzzle (current): b = 2^(2^n) mod N. The sealer knows φ(N) and
//     computes b instantly; the opener must run n sequential squarings.
//     Unskippable — patching the page just yields a wrong key, and
//     squarings resist the ASIC speedup a hash chain would invite.
//   - Sequential SHA-256 chain (legacy links only): the old format could
//     be skipped by patching the JS; kept so old links still open.
//
// Honest caveat (documented in SECURITY.md): this is a wall-clock delay,
// not a calendar date — faster hardware opens sooner.

import { concatBytes, randomBytes } from './b64.js';

async function sha256(bytes) {
  return new Uint8Array(await crypto.subtle.digest('SHA-256', bytes));
}

let nodeCrypto = null;
const IS_NODE = typeof process !== 'undefined' && !!process.versions?.node;
async function nodeSha() {
  if (nodeCrypto === null) {
    if (!IS_NODE) {
      nodeCrypto = false;
      return nodeCrypto;
    }
    try {
      nodeCrypto = (await import('node:crypto')).default ?? (await import('node:crypto'));
    } catch {
      nodeCrypto = false;
    }
  }
  return nodeCrypto;
}

// iterations sequential SHA-256 rounds: h0 = H(seed||salt), hi = H(h{i-1}||salt)
// onProgress(done, total) is called periodically so callers can paint a
// progress bar; the browser path yields a macrotask per tick so the page
// actually repaints during a long grind.
export async function hashChain(seed, salt, iterations, onProgress) {
  const node = await nodeSha();
  if (node) {
    let h = node.createHash('sha256').update(seed).update(salt).digest();
    for (let i = 1; i < iterations; i++) {
      h = node.createHash('sha256').update(h).update(salt).digest();
      if (onProgress && i % 65536 === 0) onProgress(i, iterations);
    }
    onProgress?.(iterations, iterations);
    return new Uint8Array(h);
  }
  let h = await sha256(concatBytes(seed, salt));
  const hidden = () => typeof document !== 'undefined' && document.hidden;
  for (let i = 1; i < iterations; i++) {
    h = await sha256(concatBytes(h, salt));
    if (onProgress && i % 4096 === 0) {
      onProgress(i, iterations);
      // setTimeout is clamped to ~1s in hidden tabs — skip the paint yield
      // when there is nothing to paint or the chain stretches absurdly.
      if (!hidden()) await new Promise((r) => setTimeout(r, 0));
    }
  }
  onProgress?.(iterations, iterations);
  return h;
}

// Hashes per second on this device (used to pick `iterations` at seal time).
export async function estimateHashRate(samples = 4000) {
  const t0 = performance.now();
  await hashChain(new Uint8Array(32), new Uint8Array(16), samples);
  const dt = Math.max(performance.now() - t0, 1);
  return (samples * 1000) / dt;
}

export function iterationsFor(targetMillis, rate) {
  return Math.max(1, Math.round((targetMillis * rate) / 1000));
}

export function formatDuration(ms) {
  if (ms < 1000) return `${Math.round(ms)}ms`;
  const s = Math.round(ms / 1000);
  if (s < 60) return `${s}s`;
  const m = Math.round(s / 60);
  if (m < 60) return `${m}m`;
  const h = Math.round(m / 60);
  if (h < 48) return `${h}h`;
  return `${Math.round(h / 24)}d`;
}

// ------------------------------------------------------------ RSW puzzle
//
// Rivest–Shamir–Wagner time-lock: the payload key is folded with
// b = 2^(2^n) mod N, where N = p·q is an RSA modulus generated by the
// sealer. The sealer shortcuts via φ(N); the opener must run n sequential
// modular squarings — no trapdoor, and (unlike a raw SHA-256 chain) no
// order-of-magnitude ASIC speedup: squaring is arithmetic-bound.
// Honest caveat stands: it is a wall-clock delay, not a calendar date.

const RSW_BITS = 1024; // two 512-bit primes — factoring outruns any sane delay

export function bytesToBigInt(b) {
  let x = 0n;
  for (const v of b) x = (x << 8n) | BigInt(v);
  return x;
}

export function bigIntToBytes(x, len) {
  const out = new Uint8Array(len ?? Math.max(1, Math.ceil(x.toString(2).length / 8)));
  for (let i = out.length - 1; i >= 0 && x > 0n; i--) {
    out[i] = Number(x & 0xffn);
    x >>= 8n;
  }
  return out;
}

export function modPow(b, e, m) {
  let r = 1n;
  let x = b % m;
  while (e > 0n) {
    if (e & 1n) r = (r * x) % m;
    x = (x * x) % m;
    e >>= 1n;
  }
  return r;
}

// First primes for trial division — kills most composites before any modPow.
const SMALL_PRIMES = (() => {
  const ps = [];
  for (let n = 3; ps.length < 256; n += 2) {
    if (ps.every((p) => n % p !== 0)) ps.push(n);
  }
  return ps;
})();

function isProbablePrime(n, rounds = 16) {
  for (const p of SMALL_PRIMES) {
    if (n % BigInt(p) === 0n) return n === BigInt(p);
  }
  let d = n - 1n;
  let s = 0n;
  while ((d & 1n) === 0n) {
    d >>= 1n;
    s++;
  }
  for (let i = 0; i < rounds; i++) {
    const a = 2n + (bytesToBigInt(randomBytes(32)) % (n - 3n));
    let x = modPow(a, d, n);
    if (x === 1n || x === n - 1n) continue;
    let ok = false;
    for (let j = 1n; j < s; j++) {
      x = (x * x) % n;
      if (x === n - 1n) {
        ok = true;
        break;
      }
    }
    if (!ok) return false;
  }
  return true;
}

async function genPrime(bits) {
  const len = bits / 8;
  for (let tries = 0; ; tries++) {
    const b = randomBytes(len);
    b[0] |= 0xc0;
    b[len - 1] |= 1;
    const n = bytesToBigInt(b);
    if (isProbablePrime(n)) return n;
    if (tries % 64 === 63) await new Promise((r) => setTimeout(r, 0));
  }
}

// The session modulus: generated once, reused across links. Only the sealer
// ever knows φ(N); each link still carries its own n, so reuse is safe.
let modulusPromise = null;
export function getRswModulus() {
  if (!modulusPromise) {
    modulusPromise = (async () => {
      const [p, q] = await Promise.all([genPrime(RSW_BITS / 2), genPrime(RSW_BITS / 2)]);
      return { N: p * q, phi: (p - 1n) * (q - 1n) };
    })();
    modulusPromise.catch(() => {
      modulusPromise = null; // a failed generation must not poison the cache
    });
  }
  return modulusPromise;
}

// Sealer's shortcut: b = 2^(2^n) mod N computed in O(log n) steps via φ(N).
export function rswTrapdoor(N, phi, n) {
  const e = modPow(2n, BigInt(n), phi);
  return modPow(2n, e, N);
}

// Opener's grind: n sequential squarings mod N. Unskippable — b feeds the
// payload key directly, so editing the page just produces a wrong key.
export async function rswSolve(Nbytes, n, onProgress) {
  const N = bytesToBigInt(Nbytes);
  let x = 2n;
  let lastYield = performance.now();
  for (let i = 0; i < n; i++) {
    x = (x * x) % N;
    if ((i & 0xfff) === 0 && i !== 0) {
      onProgress?.(i, n);
      // Yield for repaints only when the page can actually paint — in a
      // hidden tab setTimeout is clamped (~1s), which would stretch the
      // grind by orders of magnitude for zero benefit.
      const hidden = typeof document !== 'undefined' && document.hidden;
      if (!hidden && performance.now() - lastYield > 50) {
        lastYield = performance.now();
        await new Promise((r) => setTimeout(r, 0));
      }
    }
  }
  onProgress?.(n, n);
  return bigIntToBytes(x, Nbytes.length);
}

// Squarings per second on this device (calibrates `n` at seal time and the
// opener's ETA). Benchmarked on a random odd 1024-bit number — primality is
// irrelevant for timing.
export async function estimateSquaringRate(samples = 50000) {
  const nb = randomBytes(RSW_BITS / 8);
  nb[0] |= 0x80;
  nb[RSW_BITS / 8 - 1] |= 1;
  const N = bytesToBigInt(nb);
  let x = 2n;
  const t0 = performance.now();
  for (let i = 0; i < samples; i++) x = (x * x) % N;
  const dt = Math.max(performance.now() - t0, 1);
  return (samples * 1000) / dt;
}
